def inline_figures(body):
    """Replace each <figure data-embed="node"> placeholder with its SVG."""
    svg_dir = HERE / "post" / "svg"
    missing = []

    def sub(m):
        node, caption = m.group(1), m.group(2)
        path = svg_dir / f"{node}.svg"
        if not path.exists():
            missing.append(node)
            return m.group(0)
        return (
            f'<figure class="fig">\n{path.read_text()}\n'
            f"<figcaption>{caption}</figcaption>\n</figure>"
        )

    out = re.sub(
        r'<figure data-embed="([^"]+)"><figcaption>(.*?)</figcaption></figure>',
        sub,
        body,
        flags=re.S,
    )
    if missing:
        raise SystemExit(f"no SVG rendered for: {', '.join(missing)}")
    return out


def post_items(posts, indent):
    """One <li> per post: lead diagram as thumbnail, then title/date/blurb."""
    pad = " " * indent
    out = []
    for post in posts:
        thumb = (HERE / "post" / "svg" / f"{post['preview']}.svg").read_text()
        out.append(
            f"""{pad}<li>
{pad}  <a class="post-thumb" href="/blog/{post['slug']}/" aria-hidden="true" tabindex="-1">
{thumb}
{pad}  </a>
{pad}  <div class="post-text">
{pad}    <a class="post-link" href="/blog/{post['slug']}/">{post['title']}</a>
{pad}    <p class="post-date"><time datetime="{post['date']}">{post['date_human']}</time></p>
{pad}    <p class="post-blurb">{post['blurb']}</p>
{pad}  </div>
{pad}</li>"""
        )
    return "\n".join(out)


